"""
Memory hub: the compile loop and memory upkeep for Lumenis's scope-tagged memory (items 2, 3, 5).

  compile()   expire fuzzy/temporary rows whose valid_until has passed (marked expired_at, never deleted),
              never promote temporary rows, and write canonical memory from verified stable rows only
              (data/memory_hub/CANONICAL.md + canonical.json, both git-ignored).
  upkeep()    daily: compile + fuzzy review report; weekly (Sunday): archive fuzzy/temporary rows older
              than 30 days that have a valid_until (permanent rows such as user statements and lore stay);
              monthly (day 1): drift check of stable facts against last month's canonical snapshot.
  import_memory_md(path)  import YAML events from a MEMORY.md (idempotent by event_id; anything not
              verified is forced to fuzzy).

Undo: every expiry/archive run writes the ids it touched to data/memory_hub/runs/<ts>.json;
restore(run_file) clears expired_at for those ids.
"""
from __future__ import annotations

import hashlib
import json
import re
import time
from datetime import datetime
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parent.parent
HUB_DIR = ROOT / "data" / "memory_hub"
RUNS_DIR = HUB_DIR / "runs"
STATE_FILE = HUB_DIR / "state.json"
CANON_JSON = HUB_DIR / "canonical.json"
CANON_SNAPSHOT = HUB_DIR / "canonical_snapshot.json"
CANON_MD = HUB_DIR / "CANONICAL.md"   # under data/ (git-ignored): memory stays off GitHub
ARCHIVE_DAYS = 30
FUZZY_REVIEW_LIMIT_BYTES = 5 * 1024


def _conn(compass):
    c = compass._connect()
    compass.fill_scopes(c)
    return c


def _write_run(kind: str, ids: list, extra: dict) -> Optional[str]:
    if not ids:
        return None
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    f = RUNS_DIR / f"{datetime.now().strftime('%Y%m%d_%H%M%S')}_{kind}.json"
    f.write_text(json.dumps({"kind": kind, "ids": ids, "at": time.time(), **extra}, indent=1))
    return str(f)


def compile(compass, dry_run: bool = False, now: Optional[float] = None) -> dict:
    """One pass of the compile loop. Returns a report; dry_run changes nothing."""
    now = now or time.time()
    with _conn(compass) as c:
        due = c.execute("SELECT id, scope FROM facts WHERE expired_at IS NULL AND scope IN ('fuzzy','temporary') "
                        "AND valid_until IS NOT NULL AND valid_until < ?", (now,)).fetchall()
        ids = [r["id"] for r in due]
        if not dry_run and ids:
            c.executemany("UPDATE facts SET expired_at=? WHERE id=?", [(now, i) for i in ids])
        canon = c.execute("SELECT id, key, value, source, verification, tag, created_at FROM facts "
                          "WHERE scope='stable' AND verification IN ('tool_verified','owner_verified') "
                          "AND expired_at IS NULL ORDER BY key, created_at").fetchall()
        temp_stable = c.execute("SELECT COUNT(*) FROM facts WHERE scope='temporary' AND verification "
                                "IN ('tool_verified','owner_verified')").fetchone()[0]
    canonical = [dict(r) for r in canon]
    report = {
        "dry_run": dry_run, "at": datetime.fromtimestamp(now).isoformat(timespec="seconds"),
        "expired": {"fuzzy": sum(1 for r in due if r["scope"] == "fuzzy"),
                    "temporary": sum(1 for r in due if r["scope"] == "temporary")},
        "canonical_count": len(canonical),
        "temporary_never_promoted": temp_stable,
        "layers": compass.layer_stats(),
    }
    if not dry_run:
        HUB_DIR.mkdir(parents=True, exist_ok=True)
        report["run_file"] = _write_run("expire", ids, {"note": "compile expiry"})
        CANON_JSON.write_text(json.dumps(canonical, indent=1, default=str))
        lines = ["# CANONICAL.md — Lumenis stable memory (generated by the compile loop; do not edit)", "",
                 f"Compiled {report['at']}. Only rows that are scope=stable AND verified by a tool or by One2lv.",
                 f"{len(canonical)} canonical facts.", ""]
        for r in canonical:
            lines.append(f"- **{r['key']}**: {str(r['value'])[:300]} ({r['verification']}, source {r['source']})")
        CANON_MD.write_text("\n".join(lines) + "\n")
    return report


def fuzzy_review(compass) -> dict:
    """Daily review: how much fuzzy memory there is, by tag, and whether it needs summarising (>5 KB)."""
    with _conn(compass) as c:
        rows = c.execute("SELECT tag, COUNT(*) n, SUM(LENGTH(value)) b FROM facts WHERE scope='fuzzy' "
                         "AND expired_at IS NULL AND COALESCE(verification,'') NOT IN ('dream','plan') "
                         "GROUP BY tag ORDER BY n DESC").fetchall()
        soon = c.execute("SELECT COUNT(*) FROM facts WHERE scope='fuzzy' AND expired_at IS NULL AND valid_until "
                         "BETWEEN ? AND ?", (time.time(), time.time() + 7 * 86400)).fetchone()[0]
    total_b = sum(r["b"] or 0 for r in rows)
    return {"fuzzy_rows": sum(r["n"] for r in rows), "fuzzy_bytes": total_b,
            "needs_summary": total_b > FUZZY_REVIEW_LIMIT_BYTES,
            "expiring_within_7_days": soon,
            "by_tag": [{"tag": r["tag"], "rows": r["n"], "bytes": r["b"]} for r in rows[:15]]}


def weekly_archive(compass, dry_run: bool = False, now: Optional[float] = None) -> dict:
    now = now or time.time()
    cutoff = now - ARCHIVE_DAYS * 86400
    with _conn(compass) as c:
        rows = c.execute("SELECT id FROM facts WHERE expired_at IS NULL AND scope IN ('fuzzy','temporary') "
                         "AND created_at < ? AND valid_until IS NOT NULL AND valid_until < ?",
                         (cutoff, now)).fetchall()
        ids = [r["id"] for r in rows]
        if not dry_run and ids:
            c.executemany("UPDATE facts SET expired_at=? WHERE id=?", [(now, i) for i in ids])
    return {"archived": len(ids), "dry_run": dry_run,
            "run_file": None if dry_run else _write_run("archive", ids, {"older_than_days": ARCHIVE_DAYS})}


def drift_check(compass) -> dict:
    """Monthly: compare stable facts with last month's snapshot; a changed or vanished value is drift."""
    with _conn(compass) as c:
        rows = c.execute("SELECT key, value FROM facts WHERE scope='stable' AND expired_at IS NULL").fetchall()
    cur: dict = {}
    for r in rows:
        cur.setdefault(r["key"], set()).add(hashlib.sha256(str(r["value"]).encode()).hexdigest()[:16])
    conflicts = sorted(k for k, v in cur.items() if len(v) > 1)
    prev = {}
    if CANON_SNAPSHOT.is_file():
        try:
            prev = json.loads(CANON_SNAPSHOT.read_text()).get("facts", {})
        except Exception:
            prev = {}
    changed = sorted(k for k in prev if k in cur and set(prev[k]) != cur[k])
    vanished = sorted(k for k in prev if k not in cur)
    HUB_DIR.mkdir(parents=True, exist_ok=True)
    CANON_SNAPSHOT.write_text(json.dumps({"at": time.time(), "facts": {k: sorted(v) for k, v in cur.items()}}))
    return {"stable_keys": len(cur), "changed": changed, "vanished": vanished,
            "conflicting_values": conflicts, "first_snapshot": not prev}


def restore(compass, run_file: str) -> dict:
    data = json.loads(Path(run_file).read_text())
    with compass._connect() as c:
        c.executemany("UPDATE facts SET expired_at=NULL WHERE id=?", [(i,) for i in data["ids"]])
    return {"restored": len(data["ids"]), "run_file": run_file}


def _load_state() -> dict:
    try:
        return json.loads(STATE_FILE.read_text())
    except Exception:
        return {}


def upkeep(compass, now: Optional[datetime] = None, force: Optional[str] = None) -> dict:
    """Run whatever upkeep is due today (or the one named in force: daily|weekly|monthly)."""
    now = now or datetime.now()
    st = _load_state()
    today = now.strftime("%Y-%m-%d")
    out: dict = {"date": today}
    if force in (None, "daily") and (force or st.get("daily") != today):
        out["compile"] = compile(compass)
        out["fuzzy_review"] = fuzzy_review(compass)
        st["daily"] = today
    if force == "weekly" or (force is None and now.weekday() == 6 and st.get("weekly") != today):
        out["weekly_archive"] = weekly_archive(compass)
        st["weekly"] = today
    if force == "monthly" or (force is None and now.day == 1 and st.get("monthly") != today):
        out["drift"] = drift_check(compass)
        st["monthly"] = today
    HUB_DIR.mkdir(parents=True, exist_ok=True)
    st["last"] = out
    STATE_FILE.write_text(json.dumps(st, indent=1, default=str))
    return out


_YAML_BLOCK = re.compile(r"```yaml\n(.*?)```", re.S)


def import_memory_md(compass, path: str) -> dict:
    """Import the YAML event lists from a MEMORY.md. Unverified events are forced to fuzzy."""
    import yaml
    text = Path(path).read_text()
    added, skipped, forced = 0, 0, 0
    for block in _YAML_BLOCK.findall(text):
        try:
            data = yaml.safe_load(block)
        except Exception:
            continue
        if not isinstance(data, list):
            continue
        for ev in data:
            if not isinstance(ev, dict) or not ev.get("event_id") or not ev.get("content"):
                continue
            key = f"memory_md.{ev['event_id']}"
            with compass._connect() as c:
                if c.execute("SELECT 1 FROM facts WHERE key=?", (key,)).fetchone():
                    skipped += 1
                    continue
            scope = ev.get("scope") or "fuzzy"
            if scope == "stable":
                scope, forced = "fuzzy", forced + 1   # nothing in a pasted file is verified
            vu = ev.get("valid_until")
            vu_ts = None
            if vu:
                try:
                    vu_ts = datetime.fromisoformat(str(vu).replace("Z", "+00:00")).timestamp()
                except Exception:
                    vu_ts = None
            compass.store_fact(key, str(ev["content"]), source=str(ev.get("source") or "memory_md"),
                               confidence=0.2, verification="unverified", scope=scope,
                               tag=str(ev.get("tag") or "MEMORY_MD"), valid_until=vu_ts)
            added += 1
    return {"added": added, "already_there": skipped, "stable_forced_to_fuzzy": forced}
