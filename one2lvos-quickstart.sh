# Deploy services
deploy_services() {
    log_step "STEP 3: Deploying One2lvOS Services"

    log_info "Starting Docker Compose deployment..."
    chmod +x deploy.sh

    log_info "Pulling Docker images..."
    docker compose -f docker-compose.production.yml pull || log_warning "Some images need to be built locally"

    log_info "Building Docker images..."
    docker compose -f docker-compose.production.yml build

    log_info "Starting all services..."
    docker compose -f docker-compose.production.yml up -d

    log_success "Services started"

    log_info "Waiting for services to stabilize (15 seconds)..."
    sleep 15
}

# Initialize Astra DB
init_astra() {
    log_step "STEP 4: Initializing Astra DB Collections"

    log_info "Setting up NVIDIA vectorize collections..."

    # Run the astra-init container
    docker compose -f docker-compose.production.yml run --rm astra-init || {
        log_warning "Astra DB initialization may have failed, but continuing..."
    }

    log_success "Astra DB initialized"
}

# Check service health
check_health() {
    log_step "STEP 5: Verifying Service Health"

    sleep 5

    # Check Nginx
    log_info "Checking Nginx Gateway..."
    if curl -f -s http://localhost:80/health > /dev/null 2>&1; then
        log_success "✓ Nginx Gateway: Healthy"
    else
        log_warning "✗ Nginx Gateway: Not responding yet (may need more time)"
    fi

    # Check Node AI Lobby
    log_info "Checking Node AI Lobby..."
    if curl -f -s http://localhost:8787/health > /dev/null 2>&1; then
        log_success "✓ Node AI Lobby: Healthy"
    else
        log_warning "✗ Node AI Lobby: Not responding yet (may need more time)"
    fi

    # Check Python Core
    log_info "Checking Python Core..."
    if curl -f -s http://localhost:3002/health > /dev/null 2>&1; then
        log_success "✓ Python Core: Healthy"
    else
        log_warning "✗ Python Core: Not responding yet (may need more time)"
    fi
}

