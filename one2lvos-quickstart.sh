# Check if Docker is installed
check_docker() {
    if ! command -v docker &> /dev/null; then
        log_error "Docker is not installed!"
        log_info "Please install Docker first: https://docs.docker.com/get-docker/"
        exit 1
    fi
    log_success "Docker is installed"
}

# Check if Docker Compose is installed
check_docker_compose() {
    if ! command -v docker compose &> /dev/null; then
        log_error "Docker Compose is not installed!"
        log_info "Please install Docker Compose v2+: https://docs.docker.com/compose/install/"
        exit 1
    fi
    log_success "Docker Compose is installed"
}

# Get installation directory
get_install_dir() {
    INSTALL_DIR="${1:-$HOME/one2lvos}"
    log_info "Installation directory: $INSTALL_DIR"

    if [ -d "$INSTALL_DIR" ]; then
        log_warning "Directory $INSTALL_DIR already exists"
        read -p "Do you want to remove it and reinstall? (y/N): " -n 1 -r
        echo
        if [[ $REPLY =~ ^[Yy]$ ]]; then
            log_info "Removing existing directory..."
            rm -rf "$INSTALL_DIR"
        else
            log_error "Installation cancelled"
            exit 1
        fi
    fi
}

# Clone repository
clone_repo() {
    log_step "STEP 1: Cloning One2lvOS Repository"

    log_info "Cloning from GitHub..."
    git clone https://github.com/one2lv-com/One2lvos.git "$INSTALL_DIR"

    cd "$INSTALL_DIR"
    log_success "Repository cloned to $INSTALL_DIR"
}

