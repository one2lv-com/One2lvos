#!/usr/bin/env python3
"""
Inform Lumenis Reactor Core about Project Tree Setup

This script informs Lumenis about the <project root>
project tree structure and the fix for hardcoded paths.

Usage:
    python3 inform-lumenis-project-tree.py
"""

import json
import os
import sys
from pathlib import Path
from datetime import datetime

# Try to import websocket client
try:
    import websockets
    import asyncio
    HAS_WEBSOCKET = True
except ImportError:
    HAS_WEBSOCKET = False
    print("⚠ websockets not installed, will save to file only")


def check_project_tree():
    """Check the current project tree setup"""

    target_path = Path(os.environ.get("ONE2LVOS_ROOT") or Path(__file__).resolve().parent)
    current_dir = Path.cwd()

    info = {
        "timestamp": datetime.now().isoformat(),
        "current_directory": str(current_dir),
        "target_path": str(target_path),
        "target_exists": target_path.exists(),
        "target_is_symlink": target_path.is_symlink(),
        "paths_match": current_dir == target_path,
    }

    if target_path.exists():
        if target_path.is_symlink():
            real_path = target_path.resolve()
            info["symlink_target"] = str(real_path)
            info["symlink_valid"] = real_path == current_dir
        else:
            info["is_real_directory"] = True

    return info


def generate_message():
    """Generate the message for Lumenis"""

    info = check_project_tree()

    message = f"""# Project Tree Setup Report

## Status

**Date**: {info['timestamp']}
**Current Directory**: `{info['current_directory']}`
**Target Path**: `{info['target_path']}`

## Setup Analysis

"""

    if info['target_exists']:
        if info['target_is_symlink']:
            symlink_target = info.get('symlink_target', 'unknown')
            if info.get('symlink_valid'):
                message += f"""✅ **Project tree correctly configured**

- Target path exists as symlink
- Symlink points to: `{symlink_target}`
- Symlink is valid and points to current repository
- All 129 hardcoded references to `<old sandbox path>/` will work

"""
            else:
                message += f"""⚠️ **Symlink exists but points elsewhere**

- Symlink target: `{symlink_target}`
- Current repo: `{info['current_directory']}`
- May need to recreate symlink with: `./setup-project-tree.sh --force`

"""
        else:
            if info['paths_match']:
                message += f"""✅ **Running directly from target location**

- Repository cloned to: `{info['target_path']}`
- No symlink needed
- All hardcoded paths work natively

"""
            else:
                message += f"""⚠️ **Directory exists but not linked**

- Target exists as real directory
- Not linked to current repository
- Run: `./setup-project-tree.sh --force`

"""
    else:
        message += f"""❌ **Target path does not exist**

- `<project root>` not found
- 129 hardcoded references will fail
- **Action required**: Run `./setup-project-tree.sh`

"""

    message += f"""## Hardcoded Path Statistics

- **Total occurrences**: 129
- **Files affected**: 57
- **File types**: .md (35), .py (12), .sh (6), .html (2), .service (2)

## Common Path Patterns

```
cd <project root>                    # 45 times
<project root>/                      # 38 times
<project root>/logs/                 # 12 times
WorkingDirectory=<project root>      # 8 times
ExecStart=<project root>/script.py   # 6 times
```

## Solution Implemented

The `setup-project-tree.sh` script:

1. Detects current repository location
2. Creates `<old sandbox path>/` directory if needed
3. Creates symlink: `<project root> → current_repo`
4. Makes all hardcoded paths work transparently

## Integration

This setup is now integrated into:

- ✓ `build.sh` - Runs setup before building
- ✓ `startos.sh` - Runs setup before starting services
- ✓ Build scripts automatically call setup

## VFS Migration

Long-term solution: Virtual File System (VFS)

See `VFS_README.md` for portable path abstraction that auto-detects
project root regardless of location.

## Lumenis Memory Context

This information has been logged to your memory system for future reference.
When users encounter path issues, you can reference this setup.

---

**Generated by**: inform-lumenis-project-tree.py
**Repository**: github.com/one2lv-com/One2lvos
"""

    return message, info


async def send_to_lumenis(message, info):
    """Send message to Lumenis via WebSocket"""

    if not HAS_WEBSOCKET:
        print("⚠ WebSocket not available, skipping live notification")
        return False

    try:
        uri = "ws://localhost:8000/ws"
        async with websockets.connect(uri, timeout=5) as websocket:

            payload = {
                "type": "system_notification",
                "category": "project_tree_setup",
                "message": message,
                "metadata": info
            }

            await websocket.send(json.dumps(payload))
            print("✓ Sent to Lumenis Reactor Core via WebSocket")
            return True

    except Exception as e:
        print(f"⚠ Could not connect to Lumenis: {e}")
        return False


def save_to_file(message, info):
    """Save message to file for Lumenis to read"""

    # Save to VFS structure if available
    data_dir = Path(os.environ.get("ONE2LVOS_ROOT") or Path(__file__).resolve().parent) / "data"
    if not data_dir.exists():
        data_dir = Path.cwd() / "data"

    data_dir.mkdir(parents=True, exist_ok=True)

    # Save markdown report
    report_file = data_dir / "project_tree_setup_report.md"
    report_file.write_text(message)
    print(f"✓ Saved report to: {report_file}")

    # Save JSON data
    json_file = data_dir / "project_tree_setup_info.json"
    json_file.write_text(json.dumps(info, indent=2))
    print(f"✓ Saved data to: {json_file}")

    return True


def main():
    print("🔍 Analyzing Project Tree Setup...")
    print()

    message, info = generate_message()

    # Print status
    print(message)

    # Save to files
    save_to_file(message, info)

    # Try to send to Lumenis
    if HAS_WEBSOCKET:
        print()
        print("📡 Attempting to notify Lumenis Reactor Core...")
        asyncio.run(send_to_lumenis(message, info))

    print()
    print("✅ Project tree information prepared for Lumenis")
    print()
    print("Lumenis can access this via:")
    print("  - VFS: vfs.get_data_path('project_tree_setup_report.md')")
    print("  - Direct: data/project_tree_setup_report.md")


if __name__ == "__main__":
    main()
